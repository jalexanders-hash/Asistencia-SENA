function parseDate(dStr) {
  const parts = dStr.split('/');
  return `${parseInt(parts[1], 10)}/${parseInt(parts[0], 10)}/2026`;
}

newData.forEach(studentData => {
  const student = courseData.asistencias_aprendices.find(a => a.numero_documento === studentData.documento);
  if (student) {
    for (const [dateStr, status] of Object.entries(studentData.asistencia)) {
      const realDate = parseDate(dateStr);
      if (!courseData.fechas_asistencia.includes(realDate)) {
        courseData.fechas_asistencia.push(realDate);
      }
      
      let finalStatus = '';
      if (status === 'A') finalStatus = '';
      else if (status === 'F') finalStatus = 'X';
      else if (status === 'T') finalStatus = 'Tarde';
      
      if (finalStatus) {
        student.registros[realDate] = finalStatus;
      } else {
        delete student.registros[realDate];
      }
    }
  }
});

courseData.fechas_asistencia.sort((a, b) => new Date(a).getTime() - new Date(b).getTime());

